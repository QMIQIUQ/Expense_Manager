import { expect, test } from '@playwright/test';
test('two real tabs preserve simultaneous writes and recover after closing a lease owner', async ({ context }) => {
  const first = await context.newPage(); const second = await context.newPage();
  const load = async (page: typeof first) => { await page.goto('/test-fixtures/outbox.html'); await expect(page.locator('#ready')).toHaveText('true'); };
  await load(first); await first.locator('#clear').click(); await expect(first.locator('#rows')).toHaveText('[]');
  await load(second);
  await first.locator('#prefix').fill('first'); await second.locator('#prefix').fill('second');
  await Promise.all([first.locator('#enqueue').click(), second.locator('#enqueue').click()]);
  await expect(first.locator('#result')).toHaveText('"enqueued"');
  await expect(second.locator('#result')).toHaveText('"enqueued"');
  const read = async (page: typeof first) => JSON.parse(await page.locator('#rows').innerText()) as Array<{ id: string; sequence: number; lease?: { token: string }; payload: { id: string } }>;
  await expect.poll(async () => (await read(first)).length).toBe(80);
  await expect.poll(async () => (await read(second)).length).toBe(80);
  const rows = await read(first);
  expect(new Set(rows.map((row) => row.id)).size).toBe(80);
  expect(new Set(rows.map((row) => row.sequence)).size).toBe(80);
  await Promise.all([first.locator('#claim').click(), second.locator('#claim').click()]);
  await expect(first.locator('#claim-output')).not.toBeEmpty(); await expect(second.locator('#claim-output')).not.toBeEmpty();
  const claimA = JSON.parse(await first.locator('#claim-output').innerText());
  const claimB = JSON.parse(await second.locator('#claim-output').innerText());
  expect(claimA.id).not.toBe(claimB.id);
  await second.locator('#complete').click(); await expect(second.locator('#result')).toHaveText('true');
  await first.close(); await second.close();
  const reopened = await context.newPage();
  await reopened.clock.setFixedTime(Date.now() + 61000);
  await load(reopened);
  await expect.poll(async () => (await read(reopened)).length).toBe(79);
  await reopened.locator('#claim').click(); await expect(reopened.locator('#claim-output')).not.toBeEmpty();
  const recovered = JSON.parse(await reopened.locator('#claim-output').innerText());
  expect(recovered.id).toBe(claimA.id);
  expect(recovered.lease.token).not.toBe(claimA.lease.token);
  await reopened.locator('#complete').click(); await expect(reopened.locator('#result')).toHaveText('true');
  await expect.poll(async () => (await read(reopened)).length).toBe(78);
});

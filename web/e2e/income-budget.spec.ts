import { expect, test } from '@playwright/test';
test('income-linked policy saves offline, survives reload, syncs and restores manual mode', async ({ page, context }) => {
  await page.goto('/test-fixtures/income-budget.html');
  await expect(page.getByRole('button', { name: 'Edit budget', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Edit budget', exact: true }).click();
  await page.getByLabel('Budget mode', { exact: true }).selectOption('income');
  await page.getByLabel('Income allocated to budget (%)', { exact: true }).fill('75');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByLabel('Budget mode', { exact: true })).toHaveCount(0);
  await expect(page.locator('#mode')).toHaveText('true');
  await expect(page.locator('.income-budget-summary')).toContainText('RM3750.00');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Edit budget', exact: true }).click();
  await page.getByLabel('Income allocated to budget (%)', { exact: true }).fill('70');
  await page.screenshot({ path: 'test-results/income-budget-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByLabel('Budget mode', { exact: true })).toHaveCount(0);
  await context.setOffline(false);
  await page.reload();
  await expect(page.locator('#mode')).toHaveText('true');
  await page.getByRole('button', { name: 'Sync queued changes' }).click();
  await expect(page.locator('#sync-status')).toHaveText('{"success":2,"failed":0,"remaining":0}');
  await expect(page.locator('#remote')).toContainText('"percentage":70');
  await expect(page.locator('#remote')).toContainText('"monthly":1500');
  await page.getByRole('button', { name: 'Edit budget', exact: true }).click();
  await page.getByLabel('Budget mode', { exact: true }).selectOption('manual');
  await expect(page.getByLabel('Maximum amount (MYR)')).toHaveValue('1500.00');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('#mode')).toHaveText('false');
  await expect(page.getByLabel('Budget mode', { exact: true })).toHaveCount(0);
});
